def ver_tabela_resultados():
    """Gera uma tabela visual com Pandas dos jogos finalizados."""
    global BIBLIOTECA_CONFRONTOS
    dados_tabela = []

    # Varre todas as modalidades e confrontos
    for lista_confrontos in BIBLIOTECA_CONFRONTOS.values():
        for jogo in lista_confrontos:
            if jogo.vencedor: # Apenas jogos finalizados
                # Identifica quem perdeu
                perdedor = jogo.time_b if jogo.vencedor == jogo.time_a else jogo.time_a

                dados_tabela.append({
                    "ID Jogo": jogo.id,
                    "Modalidade": jogo.modalidade,
                    "Vencedor": jogo.vencedor,
                    "Perdedor": perdedor,
                    "Placar Detalhado": ", ".join(jogo.placar_detalhado) # Formata lista em string
                })

    if not dados_tabela:
        print("\n⚠ Nenhum resultado registrado ainda.")
        return

    print("\n--- TABELA DE RESULTADOS ---")
    df = pd.DataFrame(dados_tabela)
    # Ajusta exibição do Pandas para não cortar colunas
    pd.set_option('display.max_columns', None)
    pd.set_option('display.width', 1000)
    print(df.to_string(index=False))
    print("----------------------------")

def registrar_resultado():
    global BIBLIOTECA_CONFRONTOS
    print("\n--- Registrar Resultados ---")

    # Filtra jogos agendados que ainda não têm vencedor definido
    jogos_pendentes = [j for l in BIBLIOTECA_CONFRONTOS.values() for j in l if j.data_hora and not j.vencedor]

    if not jogos_pendentes:
        return print("⚠ Nenhum jogo pendente de resultado.")

    for i, j in enumerate(jogos_pendentes):
        print(f"{i+1} - {j.modalidade} | {j.time_a} vs {j.time_b}")

    try:
        esc = int(input("Escolha o jogo: "))
        alvo = jogos_pendentes[esc - 1]
    except:
        return print("Escolha inválida.")

    # 1. Definir Vencedor
    print(f"\nQuem venceu?\n1 - {alvo.time_a}\n2 - {alvo.time_b}")
    opt_venc = input("Opção: ")

    if opt_venc == '1':
        ganhador = alvo.time_a
        perdedor = alvo.time_b
    elif opt_venc == '2':
        ganhador = alvo.time_b
        perdedor = alvo.time_a
    else:
        return print("Opção inválida.")

    alvo.vencedor = ganhador

    # 2. Loop de Placar (Sets/Tempos)
    print("\n--- Adicionar Placar (Sets/Tempos) ---")
    print("Digite a pontuação. Digite 'finalizado' para encerrar.")

    placar_temp = []
    set_count = 1

    while True:
        p_ganhador = input(f"Pontos do Ganhador ({ganhador}) no {set_count}º tempo/set: ")
        if p_ganhador.lower() == 'finalizado': break

        p_perdedor = input(f"Pontos do Perdedor ({perdedor}) no {set_count}º tempo/set: ")
        if p_perdedor.lower() == 'finalizado': break

        try:
            # Valida se são números inteiros
            pi_ganhador = int(p_ganhador)
            pi_perdedor = int(p_perdedor)

            # Salva no formato "Ganhador-Perdedor" (ex: "25-10")
            placar_temp.append(f"{pi_ganhador}-{pi_perdedor}")
            set_count += 1
        except ValueError:
            print("⚠ Por favor, digite números inteiros para os pontos.")

    alvo.placar_detalhado = placar_temp
    print(f"✅ Resultado salvo: {ganhador} venceu ({', '.join(placar_temp)})")

