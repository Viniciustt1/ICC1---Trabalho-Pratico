def gerar_chaveamento():
    global BIBLIOTECA_CONFRONTOS
    print("\n--- Gerar Chaveamento ---")
    mods = sorted(list(set(a.modalidade_final for a in BIBLIOTECA_ATLETAS.values())))
    if not mods: return print("⚠ Sem atletas.")
    for i, m in enumerate(mods): print(f"{i+1} - {m}")
    try: mod = mods[int(input("Opção: "))-1]
    except: return

    base_esporte = next((e for e in ESPORTES_PERMITIDOS if e in mod), "Futsal")
    min_req = MINIMO_JOGADORES.get(base_esporte, 1)
    candidatos = set(a.time_secretaria for a in BIBLIOTECA_ATLETAS.values() if a.modalidade_final == mod)
    qualificados = []

    print(f"\nVerificando quórum ({min_req} jogadores)...")
    for time in candidatos:
        qtd = sum(1 for a in BIBLIOTECA_ATLETAS.values() if a.modalidade_final == mod and a.time_secretaria == time)
        if qtd >= min_req: qualificados.append(time)
        else: print(f"❌ {time} eliminado ({qtd} atletas).")

    if len(qualificados) < 2: return print("⚠ Times insuficientes.")
    random.shuffle(qualificados)
    confrontos = []
    for i in range(0, len(qualificados), 2):
        ta = qualificados[i]
        tb = qualificados[i+1] if i+1 < len(qualificados) else None
        confrontos.append(Confronto(i+1, mod, ta, tb))
    BIBLIOTECA_CONFRONTOS[mod] = confrontos
    for c in confrontos: print(c)

def alocar_jogos():
    global AGENDA, BIBLIOTECA_CONFRONTOS, DISPONIBILIDADE_TIMES
    print("\n--- Agendar Jogos ---")
    mods = [m for m, l in BIBLIOTECA_CONFRONTOS.items() if l]
    if not mods: return print("⚠ Sem chaveamentos.")

    for i, m in enumerate(mods): print(f"{i+1} - {m}")
    try: mod = mods[int(input("Opção: "))-1]
    except: return

    pendentes = [c for c in BIBLIOTECA_CONFRONTOS[mod] if not c.data_hora]
    if not pendentes: return print("✅ Tudo agendado.")

    for i, c in enumerate(pendentes): print(f"{i+1} - {c.time_a} vs {c.time_b or 'BYE'}")
    try: jogo = pendentes[int(input("Jogo: "))-1]
    except: return

    ta, tb = jogo.time_a, jogo.time_b
    if tb and ta in DISPONIBILIDADE_TIMES and tb in DISPONIBILIDADE_TIMES:
        if mod in DISPONIBILIDADE_TIMES[ta] and mod in DISPONIBILIDADE_TIMES[tb]:
            print(f"\n✨ Cruzando horários para {ta} e {tb}...")
            da = DISPONIBILIDADE_TIMES[ta][mod]
            db = DISPONIBILIDADE_TIMES[tb][mod]
            sugs = []
            for dia in ["Segunda", "Terça", "Quarta", "Quinta", "Sexta"]:
                comuns = sorted(list(set(da.get(dia,[])).intersection(set(db.get(dia,[])))))
                for h in comuns: sugs.append(f"{dia} às {h}")

            if sugs:
                for i, s in enumerate(sugs): print(f"{i+1} - {s}")
                print("0 - Manual")
                try:
                    esc = int(input("Escolha: "))
                    if esc > 0:
                        sem, hora = sugs[esc-1].split(' às ')
                        dt = input(f"Data para {sem} (DD/MM/AAAA): ") + f" {hora}"
                    else: raise Exception
                except: dt = input("Data/Hora (DD/MM/AAAA HH:MM): ")
            else: print("⚠ Sem compatibilidade."); dt = input("Data/Hora (DD/MM/AAAA HH:MM): ")
        else: print("ℹ Dados de disponibilidade incompletos."); dt = input("Data/Hora (DD/MM/AAAA HH:MM): ")
    else: print("ℹ Times sem dados de disponibilidade."); dt = input("Data/Hora (DD/MM/AAAA HH:MM): ")

    try:
        jogo.data_hora = datetime.strptime(dt, "%d/%m/%Y %H:%M")
        jogo.local = input("Local: ")
        AGENDA.append({'id': jogo.id, 'modalidade': jogo.modalidade, 'time_a': jogo.time_a,
                       'time_b': str(jogo.time_b), 'data_hora': dt, 'local': jogo.local})
        print("✅ Agendado!")
    except: print("❌ Data inválida.")

