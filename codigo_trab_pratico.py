def importar_atletas_excel():
    """Importa lista de atletas com validação estrita (Regex/Listas)."""
    print("\n--- Importação de Atletas ---")
    caminho = input("Arquivo (ex: atletas.xlsx): ")
    if not os.path.exists(caminho): return print("❌ Arquivo não encontrado.")

    try: df = pd.read_excel(caminho)
    except Exception as e: return print(f"❌ Erro: {e}")

    global BIBLIOTECA_ATLETAS
    proximo_id = (max(BIBLIOTECA_ATLETAS.keys()) + 1) if BIBLIOTECA_ATLETAS else 1
    sucessos = 0
    erros = 0

    for index, row in df.iterrows():
        try:
            nome_raw = str(row['Nome Completo']).strip()
            padrao = re.compile(r'^[a-zA-ZáàâãéèêíïóôõöúçñÁÀÂÃÉÈÊÍÏÓÔÕÖÚÇÑ\s]+$')
            if not padrao.match(nome_raw): erros += 1; continue
            nome = nome_raw.title()

            contato = str(row['Telefone']).strip()

            sexo = str(row['Gênero']).strip().lower()
            if sexo not in GENERO_PERMITIDO: erros += 1; continue

            mod_raw = str(row['Modalidade']).strip().title()
            if mod_raw == "Vôlei De Areia": mod_raw = "Vôlei de areia"
            if mod_raw == "Tênis De Campo": mod_raw = "Tênis de campo"
            if mod_raw not in ESPORTES_PERMITIDOS: erros += 1; continue

            sec_raw = str(row['Secretaria Acadêmica']).strip()
            if sec_raw.upper() == "CAASO": sec_raw = "AAACSC (CAASO)"
            if sec_raw not in SECRETARIAS_VALIDAS: erros += 1; continue

            novo = Atleta(proximo_id, nome, contato, sexo, mod_raw, sec_raw)
            BIBLIOTECA_ATLETAS[proximo_id] = novo
            proximo_id += 1
            sucessos += 1
        except:
            erros += 1; continue

    print(f"✅ Importação concluída. Sucessos: {sucessos} | Erros: {erros}")

def importar_disponibilidade_excel():
    """Lê grades de disponibilidade (0,1,2) das abas do Excel."""
    print("\n--- Importação de Disponibilidade ---")
    caminho = input("Arquivo (ex: INTERCURSOS-2026.xlsx): ")
    if not os.path.exists(caminho): return print("❌ Arquivo não encontrado.")

    global DISPONIBILIDADE_TIMES
    try: xls = pd.read_excel(caminho, sheet_name=None, header=None)
    except Exception as e: return print(f"❌ Erro: {e}")

    print("Processando...")
    dias_semana = ["Segunda", "Terça", "Quarta", "Quinta", "Sexta"]
    horarios = ["18:00", "19:00", "20:00", "21:00"]
    count = 0

    for sheet_name, df in xls.items():
        nome_sec = sheet_name.strip()
        for sv in SECRETARIAS_VALIDAS:
            if sheet_name.upper() in sv.upper() or sv.split(' ')[0].upper() in sheet_name.upper():
                nome_sec = sv; break

        if nome_sec not in DISPONIBILIDADE_TIMES: DISPONIBILIDADE_TIMES[nome_sec] = {}

        for nome_planilha, nome_sistema in DE_PARA_MODALIDADES.items():
            locs = np.where(df == nome_planilha)
            if len(locs[0]) > 0:
                r, c = locs[0][0], locs[1][0]
                try:
                    bloco = df.iloc[r+2 : r+6, c+1 : c+6].to_numpy()
                    agenda = {}
                    for d, dia in enumerate(dias_semana):
                        agenda[dia] = []
                        for h, hora in enumerate(horarios):
                            if bloco[h][d] == 1: agenda[dia].append(hora)
                    DISPONIBILIDADE_TIMES[nome_sec][nome_sistema] = agenda
                except: continue
        count += 1
    print(f"✅ Disponibilidade de {count} abas processada.")

